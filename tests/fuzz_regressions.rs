/// Run `f` on a worker thread. Fail if it panics or does not return within the deadline.
fn bounded<T: Send + 'static>(name: &str, f: impl FnOnce() -> T + Send + 'static) -> T {
    let (tx, rx) = mpsc::channel();
    std::thread::spawn(move || {
        let _ = tx.send(f());
    });
    match rx.recv_timeout(Duration::from_secs(10)) {
        Ok(v) => v,
        Err(mpsc::RecvTimeoutError::Disconnected) => panic!("{name}: decoder panicked"),
        Err(mpsc::RecvTimeoutError::Timeout) => panic!("{name}: decoder did not return within 10s"),
    }
}

#[test]
fn jpeg_app14_segment_past_end_is_rejected() {
    let r = bounded("jpeg", || transcode::jpeg::decode(JPEG_APP14_OOB).map(|_| ()));
    assert!(r.is_err(), "expected Err, got {r:?}");
}

#[test]
fn flac_unterminated_metadata_is_rejected() {
    let r = bounded("flac", || transcode::flac::decode(FLAC_METADATA_HANG).map(|_| ()));
    assert!(r.is_err(), "expected Err, got {r:?}");
}

#[test]
fn slac_frame_count_does_not_drive_allocation() {
    let r = bounded("slac", || transcode::codec::decode(SLAC_HUGE_ALLOC).map(|_| ()));
    assert!(r.is_err(), "expected Err, got {r:?}");
}

#[test]
fn aac_fill_element_zero_escape_is_rejected() {
    let r = bounded("aac", || transcode::aac::decode_pcm(AAC_FILL_UNDERFLOW).map(|_| ()));
    assert!(r.is_err(), "expected Err, got {r:?}");
}
