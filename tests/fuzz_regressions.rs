/// Run `f` on a worker thread. Fail if it panics or does not return within the deadline.
fn bounded<T: Send + 'static>(name: &str, f: impl FnOnce() -> T + Send + 'static) -> T {
    let (tx, rx) = mpsc::channel();
    std::thread::spawn(move || {
        let _ = tx.send(f());
    });
    match rx.recv_timeout(Duration::from_secs(10)) {
        Ok(v) => v,
        Err(mpsc::RecvTimeoutError::Disconnected) => panic!("{name}: decoder panicked"),
        Err(mpsc::RecvTimeoutError::Timeout) => panic!("{name}: decoder did not return within 10s"),
    }
}

