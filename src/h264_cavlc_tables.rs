/// coeff_token: returns (len, code). nc may be negative for chroma DC.
fn coeff_token(total_coeff: usize, trailing_ones: usize, nc: i32) -> (u32, u32) {
    if nc < 0 {
        let (l, c) = COEFF_TOKEN_CDC[trailing_ones][total_coeff];
        return (l as u32, c as u32);
    }
    if nc >= 8 {
        // FLC: 6 bits. code = ((total_coeff-1)<<2)|trailing_ones, except TC==0 → 3.
        let code = if total_coeff == 0 {
            3
        } else {
            (((total_coeff as u32 - 1) << 2) | trailing_ones as u32) & 0x3F
        };
        return (6, code);
    }
    let ctx = if nc < 2 { 0 } else if nc < 4 { 1 } else { 2 };
    let (l, c) = COEFF_TOKEN[ctx][trailing_ones][total_coeff];
    (l as u32, c as u32)
}

